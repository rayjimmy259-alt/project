export const products: Product[] = rawProducts.map(buildProduct);

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getSimilarProducts(product: Product, count: number = 6): Product[] {
  const priceRange = product.price * 0.4;
  return products
    .filter(
      (p) =>
        p.id !== product.id &&
        p.category === product.category &&
        Math.abs(p.price - product.price) <= priceRange
    )
    .slice(0, count);
}
